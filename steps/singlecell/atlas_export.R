suppressPackageStartupMessages(library(SeuratObject))
root <- Sys.getenv("SLE_RUN_ROOT")
stopifnot(nzchar(root))
input <- file.path(root, "SLE/GSE135779_pipeline/data/processed/02_annotated_seurat.rds")
object <- readRDS(input)
metadata <- as.data.frame(object@meta.data, stringsAsFactors = FALSE)
metadata$cell_id <- rownames(metadata)
reduction_names <- names(object@reductions)
umap_name <- if ("umap" %in% reduction_names) "umap" else grep("umap", reduction_names, ignore.case = TRUE, value = TRUE)[[1]]
atlas_umap <- SeuratObject::Embeddings(object, reduction = umap_name)
atlas <- data.frame(cell_id = rownames(atlas_umap), UMAP_1 = atlas_umap[, 1], UMAP_2 = atlas_umap[, 2], metadata[rownames(atlas_umap), c("sample_id", "subject_id", "cohort", "condition", "cell_type_analysis", "seurat_clusters"), drop = FALSE], row.names = NULL, check.names = FALSE)
out <- file.path(root, "SLE_R1/Try/R2_13_14_15_single_cell/mapping_reference_atlas.rds")
dir.create(dirname(out), recursive = TRUE, showWarnings = FALSE)
saveRDS(atlas, out)
legacy <- file.path(root, "SLE_v1/results/exploratory_program_landscape/05_single_cell_trajectory/checkpoints/full_atlas_umap_metadata.rds")
dir.create(dirname(legacy), recursive = TRUE, showWarnings = FALSE)
saveRDS(atlas, legacy)
stopifnot(!anyDuplicated(atlas$cell_id))
